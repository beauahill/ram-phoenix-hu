# Run from the repo root: python3 tools/gen_truck.py  (regenerates TruckOutline.java)
#
# INPUT IS LOCAL-ONLY. The source drawing (docs/assets/ram-3500-blueprint.jpg) is a
# dwgmodels.com blueprint sold under a per-user licence that does not allow
# redistribution, so it is git-ignored and must NOT be committed. Keep your own
# copy at that path (or point BLUEPRINT at it). Only the traced outline
# (TruckOutline.java) lives in the repo.
"""Trace the Ram 3500 top view (crop coords: x = length from nose, y = width,
centreline y=146) into unit coordinates nose-up: ux = y - 6 (0..280), uy = x - 18 (0..673).
Emits TruckOutline.java and truck.svg (fragment)."""
from PIL import Image
import numpy as np, json
import os, sys
BLUEPRINT=os.environ.get('BLUEPRINT','docs/assets/ram-3500-blueprint.jpg')
if not os.path.exists(BLUEPRINT):
    sys.exit(f"missing {BLUEPRINT}: the blueprint is licensed and local-only, see header")
im=Image.open(BLUEPRINT).convert('L')
top=im.crop((60,340,770,620)); a=np.array(top)<150
CY=146.0
def env(x):
    ys=np.where(a[:,x])[0]; return (int(ys.min()), int(ys.max())) if len(ys) else (None,None)

# ---- outer body outline from the envelope (mirrors + text excluded, symmetrised) ----
pts_top=[]
for x in range(20, 668, 4):
    if 192 <= x <= 236:      # mirror columns: use the running-board edge
        y0 = 28
    else:
        y0,y1=env(x)
        if y0 is None: continue
    pts_top.append((x, y0))
# front nose + rear tail by hand (the envelope is noisy there)
nose=[(18,96),(19,84),(22,74),(27,64),(34,55),(43,47),(54,40),(66,35),(80,32)]
tail=[(666,42),(676,44),(684,48),(689,56),(691,70),(691,146)]
top_edge=nose+[p for p in pts_top if 80<p[0]<666]+tail
# mirror for bottom edge (y' = 2*CY - y), reversed
bottom_edge=[(x, 2*CY-y) for (x,y) in reversed(top_edge)]
body=top_edge+bottom_edge

def U(x,y): return (round(y-6,1), round(x-18,1))      # to unit coords (nose up)
def poly(ps): return [U(x,y) for x,y in ps]
def rect(x0,y0,x1,y1): return (round(y0-6,1), round(x0-18,1), round(y1-6,1), round(x1-18,1))  # l,t,r,b in unit coords
def sym(y): return 2*CY-y

feat = {
 'BODY': poly(body),
 'HOOD_BULGE': rect(30,100,146,192),
 'WINDSHIELD': poly([(148,64),(238,74),(238,218),(148,228)]),
 'COWL_BOW': U(140,146),
 'ROOF': rect(240,70,395,222),
 'REAR_WINDOW': poly([(395,74),(447,82),(447,210),(395,218)]),
 'LAMPS': [rect(243,y-4,252,y+4) for y in (95,120,146,172,197)],
 'HEADLIGHTS': [poly([(20,62),(38,58),(40,92),(24,96)]), poly([(20,sym(62)),(38,sym(58)),(40,sym(92)),(24,sym(96))])],
 'TAILLIGHTS': [rect(670,46,688,66), rect(670,sym(66),688,sym(46))],
 'DOOR_SEAMS': [poly([(150,34),(150,66)]), poly([(297,34),(297,66)]), poly([(447,34),(447,66)]),
                poly([(150,sym(34)),(150,sym(66))]), poly([(297,sym(34)),(297,sym(66))]), poly([(447,sym(34)),(447,sym(66))])],
 'BOARDS': [rect(190,27,420,34), rect(190,sym(34),420,sym(27))],
 'MIRRORS': [poly([(204,46),(213,46),(231,8),(222,8)]), poly([(204,sym(46)),(213,sym(46)),(231,sym(8)),(222,sym(8))])],
 'BED': rect(450,39,668,253),
 'BED_FLOOR': rect(456,50,662,244),
 'TAILGATE': rect(668,42,690,250),
 'CAB_BACK': poly([(447,40),(447,252)]),
 # wheels (hidden under the fenders in the drawing; drawn beneath the translucent body)
 'WHEELS': [rect(90,26,170,52), rect(90,sym(52),170,sym(26)),      # FL, FR
            rect(516,22,596,50), rect(516,sym(50),596,sym(22))],   # RL, RR (outer dually)
 'WHEELS_INNER': [rect(516,52,596,74), rect(516,sym(74),596,sym(52))],
 'WIDTH': 280, 'LENGTH': 673,
}

# ---- Java ----
def jarr(flat): return ", ".join(f"{v:g}f" for v in flat)
def flat_poly(p): return [c for xy in p for c in xy]
lines=["package com.ramphoenix.launcher;","","/**"," * Top-view outline of the RAM 3500 crew cab dually, traced from the dwgmodels"," * blueprint (6941 x 2009 mm). Unit box: WIDTH x LENGTH, nose at the top,"," * x across the truck (mirror tip to mirror tip), y along it."," * Generated by tools/gen_truck.py from a local-only (licensed) blueprint;"," * edit the tracer, not this file."," */","final class TruckOutline {","    private TruckOutline() {}",
       f"    static final float WIDTH = {feat['WIDTH']}f, LENGTH = {feat['LENGTH']}f;",
       "    /** Closed body polygon, x,y pairs. */",
       f"    static final float[] BODY = {{ {jarr(flat_poly(feat['BODY']))} }};",
       f"    static final float[] WINDSHIELD = {{ {jarr(flat_poly(feat['WINDSHIELD']))} }};",
       f"    static final float[] COWL_BOW = {{ {jarr(feat['COWL_BOW'])} }};",
       f"    static final float[] REAR_WINDOW = {{ {jarr(flat_poly(feat['REAR_WINDOW']))} }};",
       f"    static final float[] CAB_BACK = {{ {jarr(flat_poly(feat['CAB_BACK']))} }};",
       "    /** Rects as l,t,r,b. */",
       f"    static final float[] HOOD_BULGE = {{ {jarr(feat['HOOD_BULGE'])} }};",
       f"    static final float[] ROOF = {{ {jarr(feat['ROOF'])} }};",
       f"    static final float[] BED = {{ {jarr(feat['BED'])} }};",
       f"    static final float[] BED_FLOOR = {{ {jarr(feat['BED_FLOOR'])} }};",
       f"    static final float[] TAILGATE = {{ {jarr(feat['TAILGATE'])} }};",
]
for name in ('LAMPS','TAILLIGHTS','BOARDS','WHEELS','WHEELS_INNER'):
    lines.append(f"    static final float[][] {name} = {{ "+", ".join("{ "+jarr(r)+" }" for r in feat[name])+" };")
for name in ('HEADLIGHTS','DOOR_SEAMS','MIRRORS'):
    lines.append(f"    static final float[][] {name} = {{ "+", ".join("{ "+jarr(flat_poly(p))+" }" for p in feat[name])+" };")
lines+=["}"]
open('apps/launcher/app/src/main/java/com/ramphoenix/launcher/TruckOutline.java','w').write("\n".join(lines)+"\n")

# ---- SVG fragment (unit coords, nose up) ----
def P(p): return "M"+" L".join(f"{x},{y}" for x,y in p)+" Z"
def L(p): return "M"+" L".join(f"{x},{y}" for x,y in p)
def R(r,rx=3,extra=''): l,t,rr,b=r; return f'<rect x="{l}" y="{t}" width="{rr-l}" height="{b-t}" rx="{rx}" {extra}/>'
BODY_FILL='rgba(255,255,255,.11)'; STROKE='rgba(255,255,255,.67)'; DET='rgba(255,255,255,.32)'; GLASS='rgba(120,185,235,.30)'
def psi_col(p): return 'rgba(255,255,255,.47)' if p is None else ('#F2A94B' if (p<30 or p>85) else '#3DD67A')
def svg(psi):
    g=[]
    for i,w in enumerate(feat['WHEELS']): g.append(R(w,4,f'fill="#2a2f3a" stroke="{psi_col(psi[i])}" stroke-width="2.2"'))
    for w in feat['WHEELS_INNER']: g.append(R(w,4,'fill="#232730" stroke="rgba(255,255,255,.25)" stroke-width="1.5"'))
    g.append(f'<path d="{P(feat["BODY"])}" fill="{BODY_FILL}" stroke="{STROKE}" stroke-width="1.8" stroke-linejoin="round"/>')
    g.append(R(feat['HOOD_BULGE'],8,f'fill="rgba(255,255,255,.06)" stroke="{DET}" stroke-width="1.2"'))
    ws=feat['WINDSHIELD']; bx,by=feat['COWL_BOW']
    g.append(f'<path d="M{ws[0][0]},{ws[0][1]} L{ws[1][0]},{ws[1][1]} L{ws[2][0]},{ws[2][1]} L{ws[3][0]},{ws[3][1]} Q{bx},{by} {ws[0][0]},{ws[0][1]} Z" fill="{GLASS}"/>')
    g.append(R(feat['ROOF'],14,f'fill="rgba(255,255,255,.12)" stroke="{DET}" stroke-width="1.2"'))
    g.append(f'<path d="{P(feat["REAR_WINDOW"])}" fill="{GLASS}"/>')
    for r in feat['LAMPS']: g.append(R(r,1.5,'fill="rgba(255,190,80,.85)"'))
    for p in feat['HEADLIGHTS']: g.append(f'<path d="{P(p)}" fill="rgba(255,236,180,.8)"/>')
    for r in feat['TAILLIGHTS']: g.append(R(r,2,'fill="rgba(229,62,62,.85)"'))
    for p in feat['DOOR_SEAMS']: g.append(f'<path d="{L(p)}" stroke="{DET}" stroke-width="1" fill="none"/>')
    g.append(f'<path d="{L(feat["CAB_BACK"])}" stroke="{DET}" stroke-width="1.2" fill="none"/>')
    for r in feat['BOARDS']: g.append(R(r,2,f'fill="rgba(255,255,255,.18)"'))
    for p in feat['MIRRORS']: g.append(f'<path d="{P(p)}" fill="rgba(255,255,255,.18)" stroke="{STROKE}" stroke-width="1.2"/>')
    g.append(R(feat['BED'],4,f'fill="none" stroke="{DET}" stroke-width="1.2"'))
    g.append(R(feat['BED_FLOOR'],3,'fill="rgba(0,0,0,.30)"'))
    g.append(R(feat['TAILGATE'],3,f'fill="rgba(255,255,255,.05)" stroke="{DET}" stroke-width="1.2"'))
    return "".join(g)
json.dump({'WIDTH':280,'LENGTH':673,'WHEELS':feat['WHEELS']}, open('truck_meta.json','w'))
open('truck_live.svgfrag','w').write(svg([38,38,40,40])); open('truck_nodata.svgfrag','w').write(svg([None]*4))
# quick standalone preview
open('truck_preview.html','w').write(f'<html><body style="background:#06070B;margin:0"><svg xmlns="http://www.w3.org/2000/svg" width="560" height="1346" viewBox="0 0 280 673">{svg([38,38,40,40])}</svg></body></html>')
print("body points:", len(feat['BODY']))
